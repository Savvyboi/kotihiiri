"""config/municipalities.yaml from its inputs (PLAN.md §18.1, M10).

Inputs, all committed:
- config/cities.yaml — the six cities, hand-edited as before;
- config/registry/municipalities_rank7-96.csv — the research registry (ranks 7–96);
- data/state/robots.json — the robots audit, one result per host (`kunta audit`);
- config/registry/rollout.yaml — which audited municipalities are switched on, batch by batch
  (M12–M14), and per-municipality overrides found by the audit;
- config/registry/electoral_districts.yaml — each municipality's 2025 candidate table at
  Statistics Finland (`statfin_candidates_table`, M15).

The output lists all 96 in rank order. A municipality from the registry is `enabled` only when its
adapter exists, every host passed the robots audit, and it is in the rollout; otherwise `reason`
says which of those failed. `kunta registry --check` fails when the committed file is stale.
"""

from __future__ import annotations

import csv
import re
from pathlib import Path
from typing import Any
from urllib.parse import parse_qs, urlsplit

import yaml

from . import jsonio
from .config import CONFIG_DIR, DATA_DIR
from .ids import slugify

REGISTRY_CSV = CONFIG_DIR / "registry" / "municipalities_rank7-96.csv"
ROLLOUT = CONFIG_DIR / "registry" / "rollout.yaml"
OUTPUT = CONFIG_DIR / "municipalities.yaml"
ROBOTS_STATE = DATA_DIR / "state" / "robots.json"

ADAPTER_BY_PLATFORM = {
    "Dynasty 10": "dynasty",
    "Tweb / KTweb": "tweb",
    "CloudNC (CaseM)": "casem",
}

# Shared providers get one rate cap across all their hosts (§18.2). Anything else is its own group.
PROVIDER_SUFFIXES = (
    "oncloudos.com",
    "cloudnc.fi",
    "tweb.fi",
    "triplancloud.fi",
    "dynastyjulkaisu.pohjoiskarjala.net",
    "dynasty.voiceintuitive.com",
)

# Registry rows named in Swedish whose Finnish name differs (Swedish-majority municipalities,
# §18.5). Their minutes are in Swedish, so `lang: sv`. Pedersöre is the same in both languages.
SWEDISH_PRIMARY = {
    "Raseborg": "Raasepori",
    "Korsholm": "Mustasaari",
    "Jakobstad": "Pietarsaari",
    "Pargas": "Parainen",
    "Mariehamn": "Maarianhamina",
    "Pedersöre": "Pedersöre",
}

ROBOTS_OK = {"allowed", "no_robots"}

HEADER = """\
# GENERATED by `kunta registry` from config/cities.yaml (the six cities),
# config/registry/municipalities_rank7-96.csv, data/state/robots.json (the robots audit),
# config/registry/rollout.yaml and config/registry/electoral_districts.yaml. Edit those, not this
# file (PLAN.md §18.1, M10).
"""


def provider_of(host: str) -> str:
    host = host.split(":", 1)[0]
    for suffix in PROVIDER_SUFFIXES:
        if host == suffix or host.endswith("." + suffix):
            return suffix
    return host


def host_of(url: str) -> str:
    return urlsplit(url).netloc


def _origin(url: str) -> str:
    p = urlsplit(url)
    return f"{p.scheme}://{p.netloc}"


def base_url(adapter: str | None, portal_url: str) -> str | None:
    """What the adapter prefixes its paths with."""
    if not portal_url:
        return None
    if adapter == "dynasty":
        # Self-hosted installs live under a path (…/dynasty10/cgi/DREQUEST.PHP, …/fi/cgi/…).
        return portal_url.split("/cgi/DREQUEST.PHP", 1)[0]
    # CloudNC paths start at /fi-FI; Tweb paths at /ktwebscr or /ktwebbin/dbisa.dll/ktwebscr.
    return _origin(portal_url)


def council_source_id(adapter: str | None, council_url: str) -> str | None:
    if not council_url:
        return None
    if adapter == "dynasty":
        ids = parse_qs(urlsplit(council_url).query).get("id")
        return ids[0] if ids else None
    if adapter == "casem":
        return urlsplit(council_url).path.rstrip("/").rsplit("/", 1)[-1]
    return None  # Tweb: the council's kirjaamo id comes from the body list (M14)


def _registry_entry(row: dict[str, str]) -> tuple[str, dict[str, Any]]:
    name = row["municipality"]
    other = row["other_name"] or None
    if name in SWEDISH_PRIMARY:
        name_fi, name_sv, lang = SWEDISH_PRIMARY[name], name, "sv"
    else:
        name_fi, name_sv, lang = name, other, "fi"
    if name_sv == name_fi or (name_sv and name_sv.endswith(" kunta")):
        name_sv = None
    adapter = ADAPTER_BY_PLATFORM.get(row["platform"])
    base = base_url(adapter, row["portal_url"]) if adapter else None
    entry: dict[str, Any] = {
        "name_fi": name_fi,
        "name_sv": name_sv,
        "rank": int(row["rank"]),
        "population": int(row["population_2025_03"]),
        "lang": lang,
        "platform": row["platform"],
        "adapter": adapter or "none",
        "provider": provider_of(host_of(base)) if base else None,
        "base_urls": [base] if base else [],
        "council_source_id": council_source_id(adapter, row["council_meetings_url"]),
        "bodies_scope": "council_board",  # §17: committees after M11
        "portal_url": row["portal_url"] or None,
        "councillors_url": row["councillors_url"] or None,
        "video_url": row["video_url"] or None,
        "registry_verification": row["verification"],
    }
    if adapter == "tweb" and "/ktwebbin/dbisa.dll/" in row["portal_url"]:
        entry["tweb_dll_paths"] = True  # every script under /ktwebbin/dbisa.dll/ (§18.1)
    return slugify(name_fi), {k: v for k, v in entry.items() if v is not None}


def _hosts(entry: dict[str, Any]) -> list[str]:
    return sorted({host_of(u) for u in entry.get("base_urls", [])})


def _gate(
    entry: dict[str, Any], robots: dict[str, dict], rollout: set[str], slug: str
) -> tuple[bool, str | None]:
    if entry["adapter"] == "none":
        return False, "no_adapter"
    statuses = [robots.get(h, {}).get("status") for h in _hosts(entry)]
    if any(s is None for s in statuses):
        return False, "robots_audit_pending"
    if any(s in ("disallowed", "partial") for s in statuses):
        return False, "robots_disallow_pending_permission"
    if any(s not in ROBOTS_OK for s in statuses):
        return False, "host_unreachable"
    if slug not in rollout:
        return False, "rollout_pending"
    return True, None


def candidate_tables(config_dir: Path = CONFIG_DIR) -> dict[str, str]:
    """{Finnish municipality name: its electoral district's 2025 candidate table}."""
    raw = yaml.safe_load((config_dir / "registry" / "electoral_districts.yaml").read_text(encoding="utf-8"))
    out: dict[str, str] = {}
    for district, d in raw["districts"].items():
        for name in d["municipalities"]:
            if name in out:
                raise ValueError(f"electoral_districts.yaml: {name} is in two districts ({district})")
            out[name] = str(d["table"])
    return out


def build(
    config_dir: Path = CONFIG_DIR,
    robots_path: Path = ROBOTS_STATE,
) -> dict[str, dict[str, Any]]:
    six = yaml.safe_load((config_dir / "cities.yaml").read_text(encoding="utf-8"))["cities"]
    rollout_raw = yaml.safe_load((config_dir / "registry" / "rollout.yaml").read_text(encoding="utf-8")) or {}
    rollout = set(rollout_raw.get("enabled") or [])
    overrides: dict[str, dict] = rollout_raw.get("overrides") or {}
    robots = jsonio.read(robots_path).get("hosts", {}) if robots_path.exists() else {}
    tables = candidate_tables(config_dir)

    out: dict[str, dict[str, Any]] = {}
    for rank, (slug, c) in enumerate(six.items(), start=1):
        entry = {"rank": rank, **c}
        if c["name_fi"] in tables:
            entry.setdefault("statfin_candidates_table", tables[c["name_fi"]])
        if c.get("base_urls"):
            entry.setdefault("provider", provider_of(host_of(c["base_urls"][0])))
        out[slug] = entry
    with (config_dir / "registry" / "municipalities_rank7-96.csv").open(encoding="utf-8") as f:
        rows = sorted(csv.DictReader(f), key=lambda r: int(r["rank"]))
    for row in rows:
        slug, entry = _registry_entry(row)
        if slug in out:
            raise ValueError(f"duplicate municipality slug {slug}")
        if entry["name_fi"] in tables:
            entry["statfin_candidates_table"] = tables[entry["name_fi"]]
        entry.update(overrides.get(slug, {}))
        enabled, reason = _gate(entry, robots, rollout, slug)
        entry["enabled"] = enabled
        if reason:
            entry["reason"] = reason
        out[slug] = entry
    names = {e["name_fi"] for e in out.values()}
    if set(tables) - names:
        raise ValueError(
            f"electoral_districts.yaml names unknown municipalities: {sorted(set(tables) - names)}"
        )
    unknown = (rollout | set(overrides)) - set(out)
    if unknown:
        raise ValueError(f"rollout.yaml names unknown municipalities: {sorted(unknown)}")
    return out


def render(municipalities: dict[str, dict[str, Any]]) -> str:
    body = yaml.safe_dump({"municipalities": municipalities}, allow_unicode=True, sort_keys=False, width=110)
    return HEADER + body


def write(path: Path = OUTPUT) -> bool:
    text = render(build())
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return False
    path.write_text(text, encoding="utf-8")
    return True


def is_stale(path: Path = OUTPUT) -> bool:
    return not path.exists() or path.read_text(encoding="utf-8") != render(build())


_SAFE = re.compile(r"^[a-z0-9]+(-[a-z0-9]+)*$")


def check_slugs(municipalities: dict[str, dict[str, Any]]) -> list[str]:
    return [s for s in municipalities if not _SAFE.match(s)]


SELF_HOSTED_BATCH = 6


def crawl_groups(selected: list[str] | None = None) -> list[dict[str, str]]:
    """The weekly matrix (§18.2): one job per enabled six-city municipality (data in git), one per
    shared provider, and batches of self-hosted municipalities (data in R2). Within a job the
    municipalities run one after another, so the provider-wide rate cap holds."""
    from .config import load_cities

    cities = load_cities()
    chosen = [s for s, c in cities.items() if c.enabled and (not selected or s in selected)]
    groups: list[dict[str, str]] = []
    shared: dict[str, list[str]] = {}
    own: list[str] = []
    for slug in chosen:
        cfg = cities[slug]
        if int(cfg.extra.get("rank", 0)) <= 6:
            groups.append({"name": slug, "cities": slug, "storage": "git"})
            continue
        provider = cfg.extra.get("provider") or ""
        if provider in PROVIDER_SUFFIXES:
            shared.setdefault(provider, []).append(slug)
        else:
            own.append(slug)
    for provider, slugs in sorted(shared.items()):
        groups.append({"name": provider, "cities": ",".join(slugs), "storage": "r2"})
    for i in range(0, len(own), SELF_HOSTED_BATCH):
        batch = own[i : i + SELF_HOSTED_BATCH]
        groups.append(
            {"name": f"self-hosted-{i // SELF_HOSTED_BATCH + 1}", "cities": ",".join(batch), "storage": "r2"}
        )
    return groups
